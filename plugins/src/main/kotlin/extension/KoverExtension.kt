import java.io.File

enum class KoverVariant(val variantName: String) {
    Presenters("presenters"),
    States("states"),
    Views("views"),
}

val koverVariants = KoverVariant.entries.map { it.variantName }

val localAarProjects = listOf(
    ":libraries:rustsdk",
    ":libraries:textcomposer:lib"
)

val excludedKoverSubProjects = listOf(
    ":appconfig",
    ":annotations",
    ":codegen",
    ":tests:testutils",
    // Exclude modules which are not Android libraries
    // See https://github.com/Kotlin/kotlinx-kover/issues/312
    ":appconfig",
    ":libraries:core",
    ":libraries:coroutines",
    ":libraries:di",
    ":libraries:rustls-tls",
    ":tests:detekt-rules",
    ":tests:konsist",
    ":tests:testutils",
) + localAarProjects

private fun Project.kover(any: Any) {
    this.dependencies.add("kover", any)
}

fun Project.setupKover() {
    // If the project is excluded from Kover, don't apply anything
    if (path in excludedKoverSubProjects) return

    // Apply the plugin
    apply(plugin = "org.jetbrains.kotlinx.kover")

    // Create verify all task joining all existing verification tasks
    tasks.register("koverVerifyAll") {
        group = "verification"
        description = "Verifies the code coverage of all subprojects."
        val dependencies = listOf(":koverVerifyMerged") + koverVariants.map { ":app:koverVerify${it.replaceFirstChar(Char::titlecase)}" }
        dependsOn(dependencies)
    }
    // https://kotlin.github.io/kotlinx-kover/
    // Run `./gradlew :app:koverHtmlReport` to get report at ./app/build/reports/kover
    // Run `./gradlew :app:koverXmlReport` to get XML report
    extensions.configure<KoverProjectExtension> {
        currentProject {
            // Create custom variants for verification
            for (variant in koverVariants) {
                createVariant(variant) {
                    defaultVariants(project)

                    // Using the cache for coverage verification seems to be flaky, so we disable it for now.
                    val taskName = "koverCachedVerify${variant.replaceFirstChar(Char::titlecase)}"
                    val cachedTask = project.tasks.findByName(taskName)
                    cachedTask?.let {
                        it.outputs.upToDateWhen { false }
                    }
                }
            }

            // Create merged variant
            createVariant("merged") {
                defaultVariants(project)
            }
        }

        // If it's the root project, set up kover for subprojects
        if (project.path == ":") {
            for (project in project.subprojects) {
                if (project.path !in excludedKoverSubProjects && File(project.projectDir, "build.gradle.kts").exists()) {
                    kover(project)
                }
            }
        }

        reports {
            filters {
                excludes {
                    classes(
                        // Exclude generated classes.
                        "*_Module",
                        "*_AssistedFactory",
                        "com.airbnb.android.showkase*",
                        "tech.orbitweb.orbitx.libraries.designsystem.showkase.*",
                        "*ComposableSingletons$*",
                        "*BuildConfig",
                        // Generated by Showkase
                        "*Ioelementandroid*PreviewKt$*",
                        "*Ioelementandroid*PreviewKt",
                        // Other
                        // We do not cover Nodes (normally covered by maestro, but code coverage is not computed with maestro)
                        "*Node",
                        "*Node$*",
                        "*Presenter\$present\$*",
                        // Forked from compose
                        "tech.orbitweb.orbitx.libraries.designsystem.theme.components.bottomsheet.*",
                        // Konsist code to make test fails
                        "tech.orbitweb.orbitx.tests.konsist.failures",
                        // Copied from Appyx
                        "tech.orbitweb.orbitx.libraries.architecture.appyx.SafeChildrenTransitionScope",
                        // DI-generated classes
                        "tech.orbitweb.orbitx.di.*Impl",
                        "tech.orbitweb.orbitx.di.*Impls",
                        "tech.orbitweb.orbitx.di.*Mirror",
                        "tech.orbitweb.orbitx.di.*Factory",
                        $$"tech.orbitweb.orbitx.*$Metro*",
                        $$"tech.orbitweb.orbitx.*$Factory*",
                        $$"tech.orbitweb.orbitx.*$Impl*",
                    )
                    annotatedBy(
                        "androidx.compose.ui.tooling.preview.Preview",
                        "tech.orbitweb.orbitx.libraries.architecture.coverage.ExcludeFromCoverage",
                        "tech.orbitweb.orbitx.libraries.designsystem.preview.*",
                    )
                }
            }

            total {
                verify {
                    // General rule: minimum code coverage.
                    rule("Global minimum code coverage.") {
                        groupBy = GroupingEntityType.APPLICATION
                        bound {
                            minValue = 70
                            // Setting a max value, so that if coverage is bigger, it means that we have to change minValue.
                            // For instance if we have minValue = 20 and maxValue = 30, and current code coverage is now 31.32%, update
                            // minValue to 25 and maxValue to 35.
                            maxValue = 80
                            coverageUnits = CoverageUnit.INSTRUCTION
                            aggregationForGroup = AggregationType.COVERED_PERCENTAGE
                        }
                    }
                }
            }
            variant(KoverVariant.Presenters.variantName) {
                verify {
                    // Rule to ensure that coverage of Presenters is sufficient.
                    rule("Check code coverage of presenters") {
                        groupBy = GroupingEntityType.CLASS

                        bound {
                            minValue = 85
                            coverageUnits = CoverageUnit.INSTRUCTION
                            aggregationForGroup = AggregationType.COVERED_PERCENTAGE
                        }
                    }
                }
                filters {
                    excludes.classes(
                        "*Fake*Presenter*",
                        "tech.orbitweb.orbitx.appnav.loggedin.LoggedInPresenter$*",
                        // Some options can't be tested at the moment
                        "tech.orbitweb.orbitx.features.preferences.impl.developer.DeveloperSettingsPresenter$*",
                        // Need an Activity to use rememberMultiplePermissionsState
                        "tech.orbitweb.orbitx.features.location.impl.common.permissions.DefaultPermissionsPresenter",
                        "*Presenter\$present\$*",
                        // Too small to be > 85% tested
                        "tech.orbitweb.orbitx.libraries.fullscreenintent.impl.DefaultFullScreenIntentPermissionsPresenter",
                    )
                    includes.inheritedFrom("tech.orbitweb.orbitx.libraries.architecture.Presenter")
                }
            }
            variant(KoverVariant.States.variantName) {
                verify {
                    // Rule to ensure that coverage of States is sufficient.
                    rule("Check code coverage of states") {
                        groupBy = GroupingEntityType.CLASS
                        bound {
                            minValue = 90
                            coverageUnits = CoverageUnit.INSTRUCTION
                            aggregationForGroup = AggregationType.COVERED_PERCENTAGE
                        }
                    }
                }
                filters {
                    excludes.classes(
                        "*State$*", // Exclude inner classes
                        "tech.orbitweb.orbitx.appnav.root.RootNavState",
                        "tech.orbitweb.orbitx.features.ftue.api.state.*",
                        "tech.orbitweb.orbitx.features.ftue.impl.welcome.state.*",
                        "tech.orbitweb.orbitx.features.messages.impl.timeline.model.bubble.BubbleState",
                        "tech.orbitweb.orbitx.libraries.designsystem.swipe.SwipeableActionsState",
                        "tech.orbitweb.orbitx.libraries.designsystem.theme.components.bottomsheet.CustomSheetState",
                        "tech.orbitweb.orbitx.libraries.maplibre.compose.CameraPositionState",
                        "tech.orbitweb.orbitx.libraries.maplibre.compose.SymbolState",
                        "tech.orbitweb.orbitx.libraries.matrix.api.room.RoomMembershipState",
                        "tech.orbitweb.orbitx.libraries.matrix.api.room.RoomMembersState",
                        "tech.orbitweb.orbitx.libraries.matrix.api.timeline.item.event.OtherState$*",
                        "tech.orbitweb.orbitx.libraries.matrix.api.timeline.item.event.LocalEventSendState*",
                        "tech.orbitweb.orbitx.libraries.mediaviewer.impl.local.pdf.PdfViewerState",
                        "tech.orbitweb.orbitx.libraries.mediaviewer.impl.local.player.MediaPlayerControllerState",
                        "tech.orbitweb.orbitx.libraries.textcomposer.model.TextEditorState",
                        "tech.orbitweb.orbitx.libraries.textcomposer.components.FormattingOptionState",
                    )
                    includes.classes("*State")
                }
            }
            variant(KoverVariant.Views.variantName) {
                verify {
                    // Rule to ensure that coverage of Views is sufficient (deactivated for now).
                    rule("Check code coverage of views") {
                        groupBy = GroupingEntityType.CLASS
                        bound {
                            // TODO Update this value, for now there are too many missing tests.
                            minValue = 0
                            coverageUnits = CoverageUnit.INSTRUCTION
                            aggregationForGroup = AggregationType.COVERED_PERCENTAGE
                        }
                    }
                }
                filters {
                    excludes.classes("*ViewKt$*") // Exclude inner classes
                    includes.classes("*ViewKt")
                }
            }
        }
    }
}

fun KoverVariantCreateConfig.defaultVariants(project: Project) {
    if (project.path == ":app") {
        addWithDependencies("gplayDebug")
    } else {
        addWithDependencies("debug", "jvm", optional = true)
    }
}
